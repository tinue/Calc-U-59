#!/usr/bin/env node
//
// The JavaScript half of Web/build.sh — run by it after the WASM engine and
// the static files are in dist/:
//
//   1. Compiles src/*.jsx into one dist/calc.js and app/app.jsx into
//      dist/app/app.js, with the vendored Babel run in Node (no npm
//      dependencies, no in-browser transform).
//   2. Copies the presets PlayCalculator offers (presets.json) from
//      examples/ into dist/presets/, with their manifest.
//   3. Stamps the PWA's service worker with a hash of the files it precaches.
//   4. Writes dist/MANIFEST.json: version, source commit, sha256 of every file.
//
// reference/WebClient.md is the contract for what dist/ contains.

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const crypto = require("crypto");
const { execFileSync } = require("child_process");

const WEB = __dirname;
const REPO = path.join(WEB, "..");
const DIST = path.join(WEB, "dist");

const read = (p) => fs.readFileSync(p, "utf8");
const sha256 = (buf) => crypto.createHash("sha256").update(buf).digest("hex");

// ---- 1. Compile ---------------------------------------------------------

const sandbox = vm.createContext({ console });
vm.runInContext(read(path.join(WEB, "vendor", "babel.min.js")), sandbox, { filename: "babel.min.js" });
const Babel = sandbox.Babel;
if (!Babel) throw new Error("vendor/babel.min.js did not expose Babel");

function compile(file) {
  try {
    return Babel.transform(read(file), {
      presets: ["react"],
      sourceType: "script",
      compact: false,
      comments: true,
    }).code;
  } catch (e) {
    throw new Error(`Babel failed on ${path.relative(WEB, file)}: ${e.message}`);
  }
}

// The one version: the Xcode project's MARKETING_VERSION, as the Qt build
// reads it (also stamped into calc.js for the Settings dialog).
const version = read(path.join(REPO, "Calc-U-59.xcodeproj", "project.pbxproj"))
  .match(/MARKETING_VERSION = ([0-9]+\.[0-9.]+);/)[1];

// In load order: helpers before the components that use them. One closure,
// so they stay out of the host page's globals; PlayCalculator.jsx hands out
// the one global.
const SOURCES = [
  "engine.js", "painters.js", "CalculatorFace.jsx", "ControlBar.jsx", "Dialogs.jsx",
  "Printer.jsx", "Debugger.jsx", "PlayCalculator.jsx",
];
const calcJs =
  "// Calc-U 59 web client — generated by Web/build.sh from Web/src/. Do not edit.\n" +
  "(function () {\n" +
  SOURCES.map((n) => `/* === ${n} === */\n` + compile(path.join(WEB, "src", n))).join("\n")
    .replace(/__CALC_VERSION__/g, version) +
  "\n})();\n";
fs.writeFileSync(path.join(DIST, "calc.js"), calcJs);
fs.writeFileSync(path.join(DIST, "app", "app.js"),
  "// Generated by Web/build.sh from Web/app/app.jsx. Do not edit.\n" +
  compile(path.join(WEB, "app", "app.jsx")));
console.log("compiled calc.js, app/app.js");

// ---- 2. Presets ---------------------------------------------------------

const presets = JSON.parse(read(path.join(WEB, "presets.json")));
fs.mkdirSync(path.join(DIST, "presets"), { recursive: true });
for (const p of presets) {
  fs.copyFileSync(path.join(REPO, "examples", p.file), path.join(DIST, "presets", p.file));
}
fs.writeFileSync(path.join(DIST, "presets", "manifest.json"), JSON.stringify(presets, null, 2) + "\n");
console.log(`presets: ${presets.map((p) => p.file).join(", ")}`);

// ---- 3. Service worker --------------------------------------------------

// Every precached path must exist, or the worker's install fails in the
// browser — caught here instead. The hash makes a new build a new cache.
const swFile = path.join(DIST, "app", "sw.js");
const sw = read(swFile);
const assets = sw.match(/const CORE_ASSETS = \[([\s\S]*?)\];/)[1].match(/"[^"]*"/g).map((s) => JSON.parse(s));
const swHash = crypto.createHash("sha256");
for (const a of assets) {
  const file = path.join(DIST, "app", a === "./" ? "index.html" : a);
  if (!fs.existsSync(file)) throw new Error(`app/sw.js precaches ${a}, which is not in dist/`);
  swHash.update(a).update(fs.readFileSync(file));
}
fs.writeFileSync(swFile, sw.replace("__CACHE_VERSION__", swHash.digest("hex").slice(0, 16)));
console.log(`app/sw.js: ${assets.length} precached files`);

// ---- 4. MANIFEST.json ---------------------------------------------------

const git = (...args) => execFileSync("git", ["-C", REPO, ...args], { encoding: "utf8" }).trim();
const commit = git("rev-parse", "HEAD") + (git("status", "--porcelain") ? "-dirty" : "");

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}
const files = {};
for (const f of walk(DIST).sort()) {
  const rel = path.relative(DIST, f).split(path.sep).join("/");
  if (rel !== "MANIFEST.json") files[rel] = sha256(fs.readFileSync(f));
}
fs.writeFileSync(path.join(DIST, "MANIFEST.json"),
  JSON.stringify({ name: "Calc-U-59-web", version, commit, files }, null, 2) + "\n");
console.log(`MANIFEST.json: ${version}, ${commit}, ${Object.keys(files).length} files`);
